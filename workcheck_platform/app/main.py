def area_summary(conditions):
    out = []
    for key, area in AREAS.items():
        checks = []
        for condition in area["conditions"]:
            status = conditions.get(condition, "NOT_RELEVANT_TO_JOB")
            tone, text = STATUS.get(status, ("none", ""))
            checks.append({"condition": condition, "check": CHECK_NAMES[condition], "status": status, "tone": tone, "text": text})
        worst = min(checks, key=lambda c: TONE_ORDER[c["tone"]])
        out.append({"key": key, "label": area["label"], "icon": area["icon"], "tone": worst["tone"], "text": worst["text"], "checks": checks})
    return out


