def _sat(t):
    return 6.106 * math.exp(17.27 * t / (237.3 + t))


def _wet_bulb(ta, rh):
    g = math.log(max(rh, 1) / 100) + 17.27 * ta / (237.3 + ta)
    td = 237.3 * g / (17.27 - g)
    ed = _sat(td)
    lo, hi = td, ta
    for _ in range(60):
        mid = (lo + hi) / 2
        ew = _sat(mid)
        if 1556 * ed - 1.484 * ed * mid - 1556 * ew + 1.484 * ew * mid + 1010 * (ta - mid) > 0:
            lo = mid
        else:
            hi = mid
    return (lo + hi) / 2


def _natural_wet_bulb(ta, rh, tg, v=1.0):
    v = max(v, 0.3)
    tp = _wet_bulb(ta, rh)
    if tg - ta >= 4:
        return tp + 0.25 * (tg - ta) + 0.1 / v ** 1.1 - 0.2
    if v > 3:
        return tp
    return ta - (0.96 + 0.069 * math.log10(v)) * (ta - tp)


def compute_wbgt(ta, rh, tg=None, tnwb=None):
    if tg is not None and tnwb is not None:
        return 0.7 * tnwb + 0.2 * tg + 0.1 * ta, "Measured globe and wet bulb"
    if tg is not None:
        return 0.7 * _natural_wet_bulb(ta, rh, tg) + 0.2 * tg + 0.1 * ta, "Measured globe, estimated wet bulb"
    return 0.7 * _natural_wet_bulb(ta, rh, ta) + 0.3 * ta, "No globe: shade estimate, may understate sun"


