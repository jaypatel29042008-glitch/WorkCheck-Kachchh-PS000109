@lru_cache(maxsize=1)
def heat_tables():
    """Monthly safe work hours for each location, workload and shift, from model hourly heat."""
    out = {}
    with ref() as rc:
        rows = rc.execute("SELECT location_id, substr(time, 6, 2) m, substr(time, 1, 10) d, CAST(substr(time, 12, 2) AS INT) h, wbgt_sun, wbgt_shade FROM location_hourly_2025").fetchall()
    shifts = {"9-18": (9, 17), "6-15": (6, 14)}
    for mode, (workload, column, _) in MODES.items():
        for shift, (a, b) in shifts.items():
            totals = {}
            for r in rows:
                if a <= r["h"] <= b:
                    key = (r["location_id"], r["d"])
                    totals[key] = totals.get(key, 0.0) + allowed_pct(r[column], workload) / 100
            monthly = {}
            for (loc, d), value in totals.items():
                monthly.setdefault(loc, {}).setdefault(int(d[5:7]), []).append(value)
            out[(mode, shift)] = {loc: [round(sum(v[m]) / len(v[m]), 2) for m in range(1, 13)] for loc, v in monthly.items()}
    return out


