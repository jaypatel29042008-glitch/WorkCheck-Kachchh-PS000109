def exposure_summary(days):
    """Five plain measures. Each says what it is and where the number comes from."""
    months = {}
    for d in days:
        m = months.setdefault(d["shift_date"][:7], {"allowed": [], "noise": [], "uv": [], "p90": 0})
        m["allowed"].append(d["allowed_work_hours"])
        m["uv"].append(d["uv_peak_index"])
        if d["noise_dose_pct"] is not None:
            m["noise"].append(d["noise_dose_pct"])
        m["p90"] = d["p90"]
    keys = sorted(months)
    mean = lambda v: sum(v) / len(v) if v else None

    summer = [d["allowed_work_hours"] for d in days if "04" <= d["shift_date"][5:7] <= "10"] or [d["allowed_work_hours"] for d in days]
    heat_value = mean(summer)
    heat_level = "high" if heat_value < 4.5 else "moderate" if heat_value < 7 else "ok"
    heat = {"key": "heat", "label": "Heat", "icon": "temperature-sun", "value": f"{heat_value:.1f}", "unit": "safe hours a shift", "caption": "April to October. Model estimate", "level": heat_level, "chip": {"high": "High", "moderate": "Moderate", "ok": "Low"}[heat_level], "series": [round(mean(months[k]["allowed"]), 1) for k in keys], "series_unit": "safe hours"}

    p75, p90 = days[-1]["p75"], days[-1]["p90"]
    if p90 <= 0:
        silica = {"key": "silica", "label": "Silica dust", "icon": "wind", "value": "None", "caption": "No silica estimate for this job", "level": "none", "chip": "No estimate", "series": []}
    else:
        silica = {"key": "silica", "label": "Silica dust", "icon": "wind", "value": f"{p75:.1f}–{p90:.1f}", "unit": "mg/m³-years", "caption": "Dose so far, from US mine samples. Review at 0.5", "level": "high" if p75 >= 0.5 else "moderate" if p90 >= 0.5 else "ok", "chip": "Above review level" if p75 >= 0.5 else "Partly above" if p90 >= 0.5 else "Below review level", "series": [round(months[k]["p90"], 2) for k in keys], "series_unit": "mg/m³-years"}

    noise_all = [d["noise_dose_pct"] for d in days if d["noise_dose_pct"] is not None]
    noise_value = mean(noise_all)
    noise = {"key": "noise", "label": "Noise", "icon": "volume", "value": f"{noise_value:.0f}%" if noise_value is not None else "None", "unit": "of daily limit" if noise_value is not None else None, "caption": "From outside studies of similar jobs" if noise_value is not None else "No noise value for this job yet", "level": "none" if noise_value is None else "high" if noise_value > 100 else "ok", "chip": "No data" if noise_value is None else "Over limit" if noise_value > 100 else "Under limit", "series": [round(mean(months[k]["noise"])) if months[k]["noise"] else None for k in keys] if noise_value is not None else [], "series_unit": "% of limit"}

    may = [d["uv_peak_index"] for d in days if d["shift_date"][5:7] == "05"]
    uv_may = mean(may) or 0
    sun = {"key": "sun", "label": "Sun", "icon": "sun", "value": f"{uv_may:.1f}" if uv_may else "Shade", "unit": "peak UV in May" if uv_may else None, "caption": "In the open. Model estimate" if uv_may else "This job is mostly in shade", "level": "high" if uv_may >= HIGH_UV else "moderate" if uv_may >= 6 else "ok", "chip": "Very high" if uv_may >= HIGH_UV else "High" if uv_may >= 6 else "Low", "series": [round(mean(months[k]["uv"]), 1) for k in keys] if uv_may else [], "series_unit": "peak UV"}

    weeks = {}
    for d in days:
        iso = date.fromisoformat(d["shift_date"]).isocalendar()
        week = weeks.setdefault((iso[0], iso[1]), {"hours": 0.0, "month": d["shift_date"][:7]})
        week["hours"] += d["shift_duration_hours"]
    peak = max((w["hours"] for w in weeks.values()), default=0)
    by_month = {}
    for w in weeks.values():
        by_month[w["month"]] = max(by_month.get(w["month"], 0), w["hours"])
    hours = {"key": "hours", "label": "Work hours", "icon": "clock-hour-9", "value": f"{peak:.0f}", "unit": "hours, busiest week", "caption": "Test pattern. Long-term limit is 55", "level": "high" if peak >= WEEK_LIMIT else "ok", "chip": "Over 55 hours" if peak >= WEEK_LIMIT else "Under 55 hours", "series": [round(by_month.get(k, 0)) for k in keys], "series_unit": "hours in busiest week"}

    labels = [date.fromisoformat(k + "-01").strftime("%b") for k in keys]
    out = [heat, silica, noise, sun, hours]
    for metric in out:
        metric["months"] = labels
    return out


