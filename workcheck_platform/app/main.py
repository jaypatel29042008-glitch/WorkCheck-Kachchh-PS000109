@lru_cache(maxsize=1)
def dust_and_compound_tables():
    """Monthly ambient PM10, PM2.5, extreme dust days, and compound double-hazard metrics per location."""
    with ref() as rc:
        rows = rc.execute("""
            SELECT location_id,
                   CAST(strftime("%m", date) AS INTEGER) - 1 AS m_idx,
                   round(avg(pm10_mean), 1) AS avg_pm10,
                   round(avg(pm25_mean), 1) AS avg_pm25,
                   sum(CASE WHEN pm10_mean > 100 THEN 1 ELSE 0 END) AS dust_days,
                   round(max(wbgt_sun_max), 1) AS max_wbgt,
                   sum(CASE WHEN hours_sun_over_27_5 >= 4 THEN 1 ELSE 0 END) AS heat_days,
                   sum(CASE WHEN hours_sun_over_27_5 >= 4 AND pm10_mean > 100 THEN 1 ELSE 0 END) AS compound_days
            FROM location_daily_2025
            GROUP BY location_id, m_idx
            ORDER BY location_id, m_idx
        """).fetchall()

    metrics = {}
    for r in rows:
        lid = r["location_id"]
        if lid not in metrics:
            metrics[lid] = {
                "pm10": [0.0] * 12,
                "pm25": [0.0] * 12,
                "dust_days": [0] * 12,
                "max_wbgt": [0.0] * 12,
                "heat_days": [0] * 12,
                "compound_days": [0] * 12,
                "compound_score": [0] * 12,
            }
        m = r["m_idx"]
        metrics[lid]["pm10"][m] = r["avg_pm10"]
        metrics[lid]["pm25"][m] = r["avg_pm25"]
        metrics[lid]["dust_days"][m] = r["dust_days"]
        metrics[lid]["max_wbgt"][m] = r["max_wbgt"]
        metrics[lid]["heat_days"][m] = r["heat_days"]
        metrics[lid]["compound_days"][m] = r["compound_days"]

    # Calculate compound score (0-100) combining heat days/WBGT stress with particulate burden
    for lid, d in metrics.items():
        for m in range(12):
            heat_factor = min(1.0, d["heat_days"][m] / 25.0)
            dust_factor = min(1.0, d["pm10"][m] / 80.0)
            c_days = d["compound_days"][m]
            score = int(round(100 * (0.45 * heat_factor + 0.35 * dust_factor + 0.20 * math.sqrt(heat_factor * dust_factor)) + (c_days * 3)))
            d["compound_score"][m] = max(0, min(100, score))

    return metrics


