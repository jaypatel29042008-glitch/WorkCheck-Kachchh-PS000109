def next_step(state, name):
    first = name.split(" ")[0]
    reasons = state["reasons"]
    others = [r["text"] for r in reasons[1:4]]
    also = "Also open: " + ", ".join(o[0].lower() + o[1:] for o in others) + "." if others else ""
    if reasons and reasons[0]["urgent"]:
        return {"title": "Collapse in heat was reported", "body": "If this is happening now, call 108 and start cooling. Review this report today.", "cta": "Review report"}
    if state["level"] == "action":
        top = reasons[0]
        if top["text"].startswith("Reported"):
            rest = top["text"].replace("Reported", "", 1).strip().lstrip(":")
            formatted_text = rest[0].upper() + rest[1:] if rest else "New symptom"
            return {"title": f"{first} reported a new symptom", "body": f"{formatted_text}. Review and decide on a check. {also}".strip(), "cta": "Review report"}
        return {"title": f"Call {first} back in", "body": f"{top['text']}. {also}".strip(), "cta": "Record result"}
    if state["level"] == "due":
        return {"title": f"Book a check for {first}", "body": f"{reasons[0]['text']}. {also}".strip(), "cta": "Record result"}
    if state["level"] == "watch":
        return {"title": "Nothing to do today", "body": f"No check has been triggered. {first}'s exposure is being watched.", "cta": None}
    return {"title": "All checks are up to date", "body": "Nothing is waiting right now.", "cta": None}


