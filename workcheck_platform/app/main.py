@lru_cache(maxsize=1)
def reference():
    with ref() as con:
        rows = lambda q: [dict(r) for r in con.execute(q)]
        workers = {r["worker_id"]: r for r in rows("SELECT * FROM sim_workers")}
        jobs = {r["job_id"]: r for r in rows("SELECT * FROM job_profiles")}
        events, conditions, assignments = {}, {}, {}
        for r in rows("SELECT * FROM sim_case_events ORDER BY date, rowid"):
            events.setdefault(r["worker_id"], []).append(r)
        for r in rows("SELECT * FROM sim_worker_condition_status"):
            conditions.setdefault(r["worker_id"], {})[r["condition"]] = r["status"]
        for r in rows("SELECT * FROM sim_worker_assignments ORDER BY start_date"):
            r["job"], r["icon"] = JOBS[r["job_id"]]
            r["place"] = PLACES.get(r["location_id"], r["taluka"])
            assignments.setdefault(r["worker_id"], []).append(r)
        table = {}
        for r in rows("SELECT * FROM rules_heat_work_table ORDER BY wbgt_max_c"):
            table.setdefault(r["workload"], []).append((r["wbgt_max_c"], r["allowed_work_pct"]))
    names = dict(NARRATIVE_NAMES)
    designed = sorted(w for w in workers if w not in names)
    for i, wid in enumerate(designed):
        names[wid] = f"{FIRST_NAMES[i % len(FIRST_NAMES)]} {LAST_INITIALS[(i * 7) % len(LAST_INITIALS)]}."
    return {"workers": workers, "jobs": jobs, "events": events, "conditions": conditions, "assignments": assignments, "table": table, "names": names}


def allowed_pct(wbgt, workload):
    for limit, pct in reference()["table"][workload]:
        if wbgt <= limit:
            return pct
    return 0


def merged_conditions(worker_id, con):
    current = dict(reference()["conditions"].get(worker_id, {}))
    for r in con.execute("SELECT condition, status FROM condition_updates WHERE worker_id = ? ORDER BY id", (worker_id,)):
        current[r["condition"]] = r["status"]
    return current


def care_tracker(worker_id):
    """Turn raw events into the one plain journey people understand, like tracking a parcel."""
    events = [e for e in reference()["events"].get(worker_id, []) if e["scripted"]]
    first = lambda *names: next((e["date"] for e in events if e["event"] in names), None)
    found, legal = first("ENROLLED", "LEGAL_EXAM_DUE"), first("LEGAL_EXAM_DUE")
    referred = first("REFERRED") or legal
    seen, advised, done, closed = first("ATTENDED"), first("FOLLOW_UP_ADVISED"), first("FOLLOW_UP_DONE"), first("CLOSED")
    lost, refound, overdue, still = first("LOST_TO_FOLLOW_UP"), first("RE_FOUND"), first("OVERDUE"), first("STILL_OPEN")
    if first("NO_REFERRAL") and not seen:
        return {"open": False, "problem": None, "summary": "Checked at enrolment. No referral was needed.", "steps": [{"key": "found", "label": "Added to record", "state": "done", "date": found}, {"key": "closed", "label": "No referral needed", "state": "done", "date": first("NO_REFERRAL")}]}
    stuck = bool((lost and not refound) or still)
    follow = "done" if done else "problem" if advised and stuck else "current" if advised else "skipped" if closed else "todo"
    steps = [{"key": "found", "label": "Added to record", "state": "done", "date": found},
             {"key": "referred", "label": "Legal exam due" if legal else "Referred", "state": "done" if referred or seen else "todo", "date": referred},
             {"key": "seen", "label": "Seen at clinic", "state": "done" if seen else "problem" if stuck else "todo", "date": seen},
             {"key": "follow", "label": "No follow-up needed" if follow == "skipped" else "Follow-up", "state": follow, "date": (done or advised) if follow != "skipped" else None},
             {"key": "closed", "label": "Closed", "state": "done" if closed else "todo", "date": closed}]
    if not any(s["state"] in ("current", "problem") for s in steps):
        for step in steps:
            if step["state"] == "todo":
                step["state"] = "current"
                break
    problem = None
    if lost and not refound:
        problem = "Lost contact with this worker"
    elif still and not seen:
        problem = "Legal exam overdue" if legal else "Clinic visit overdue"
    elif still:
        problem = "Follow-up not recorded"
    if problem:
        summary = problem
    elif closed and lost:
        summary = "Lost contact after moving, then found again with the QR pass."
    elif closed and overdue:
        summary = "The exam was late, then completed."
    elif closed:
        summary = "Case closed."
    else:
        summary = "Case in progress."
    return {"open": closed is None, "problem": problem, "summary": summary, "steps": steps}


def open_symptoms(worker_id, con):
    return [dict(r) for r in con.execute("SELECT id, at, symptom, urgent FROM symptom_reports WHERE worker_id = ? AND reviewed_at IS NULL ORDER BY urgent DESC, id DESC", (worker_id,))]


def worker_state(worker_id, con):
    """Plain rule: what is open for this worker. It describes follow-up, not disease."""
    conditions = merged_conditions(worker_id, con)
    reasons = []
    for symptom in open_symptoms(worker_id, con):
        text, area = SYMPTOMS[symptom["symptom"]]
        reasons.append({"tone": "action", "rank": -1 if symptom["urgent"] else 0, "text": f"Reported: {text.lower()}", "area": area, "condition": None, "urgent": bool(symptom["urgent"])})
    for condition, status in conditions.items():
        if condition not in CONDITION_AREA:
            continue
        tone, text = STATUS.get(status, ("none", ""))
        check = CHECK_NAMES[condition]
        if tone in ("action", "due"):
            label = {"Missed": f"{check} missed", "Follow-up open": f"{check}: follow-up open", "Due": f"{check} due", "Doctor noted (demo)": f"{check}: doctor noted (demo)"}[text]
            reasons.append({"tone": tone, "rank": 1 if tone == "action" else 2, "text": label, "area": CONDITION_AREA[condition], "condition": condition, "urgent": False})
    updated = con.execute("SELECT 1 FROM condition_updates WHERE worker_id = ? LIMIT 1", (worker_id,)).fetchone()
    problem = care_tracker(worker_id)["problem"]
    if problem and not updated:
        reasons.append({"tone": "action", "rank": 1, "text": problem, "area": None, "condition": None, "urgent": False})
    reasons.sort(key=lambda r: (r["rank"], r["text"]))
    if any(r["tone"] == "action" for r in reasons):
        level = "action"
