    for r in rows:
        t = datetime.fromisoformat(r["at"])
        if r["event"] == "in":
            started = t
        elif started is not None:
            if t.isocalendar()[:2] == week:
                total += (t - started).total_seconds() / 3600
            started = None
    return {"worker_id": item.worker_id, "hours_this_week": round(total, 2), "over_55": total >= WEEK_LIMIT}


